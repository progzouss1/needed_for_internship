    @staticmethod
    def __increase_rank(tensor, idx, epsilon):
        """
        Increases the rank of the tensor at the core given by index idx

        Parameters
        ----------
        tensor : TT
             Chebyshev Tensor in TT format.

        idx : int
             Core for which we increase rank
             Index is integer and less than the dimension of the tensor.

        epsilon : float
             Used to randomly sample values and extend rank of core

        Returns
        -------
        tensor : TT
             Chebyshev Tensor in TT format.

        Raises
        ------
        ValueError : outside interval
             The index passed is outside the accepted range. It must be greater than zero and less than the dimension of the tensor

        """

        if idx > 0 and idx < tensor.order:

            r = tensor.ranks
            n = tensor.row_dims
            tensor_new = copy.deepcopy(tensor)

            tensor_new.cores[idx - 1] = np.concatenate((tensor.cores[idx - 1],
                                                        epsilon * np.random.randn(r[idx - 1],
                                                                                  n[idx - 1], 1,
                                                                                  1)), axis=3)
            tensor_new.cores[idx] = np.concatenate((tensor.cores[idx],
                                                    epsilon * np.random.randn(1, n[idx], 1,
                                                                              r[idx + 1])), axis=0)
            tensor_new.ranks[idx] = tensor.ranks[idx] + 1

            if idx == 5 and tensor.ranks[idx] == 7:
                print(f"shape of old core at idx - 1: {tensor.cores[idx - 1].shape}")
                print(f"shape of new core at idx - 1: {tensor_new.cores[idx - 1].shape}")

                print(f"shape of old core at idx: {tensor.cores[idx].shape}")
                print(f"shape of new core at idx: {tensor_new.cores[idx].shape}")

            return tensor_new
        else:

            raise ValueError(
                "The index passed {} is outside the accepted range. It must be greater than zero and less than the dimension of the tensor".format(
                    idx))

