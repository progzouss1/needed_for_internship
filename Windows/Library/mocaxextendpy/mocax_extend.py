    def cheb_tensor_eval(self, c_tensor, scaled_pt):
        """
        This method evaluates the Chebyshev Tensor in TT format on a point that is within a hyper-rectangle defined by intervals [-1,1]. This method is used by cheb_tensor_evals at the evaluation of each point.

        Parameters
        ----------
        c_tensor : TT
             Tensor in TT format.

        scaled_pt : numpy array
             It is 1D numpy array.

        Returns
        -------
        val : float
            Evaluation value of Chebyshev tensor in TT format on scaled_pt

        Raises
        ------
        ValueError : length mismatch
             Length of scaled_pt must be equal to dimension.

        """

        if len(scaled_pt) == self.dimension:
            cheb_tensor = TTChebyshevUtils.gen_cheb_tensor(scaled_pt, self.dimension,
                                                           self.num_cheb_pts)
            val = TTChebyshevUtils.tt_tensor_inner_prod(c_tensor, cheb_tensor)
            return val
        else:
            raise ValueError("Length of scaled_pt {} must be equal to dimension {}.".format(len(scaled_pt), self.dimension))

