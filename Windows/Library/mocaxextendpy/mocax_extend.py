    def run_completion_algo(self, tensor, **kwargs):
        """
        This method runs the completion algorithm based an the Alternating Least Squares.

        Parameters
        ----------
        tensor : TT tensor
            To be modified by the algorithm

        **kwargs : dictionary with algorithm parameters
            tolerance: float
                Accuracy of approximation we want to reach (relative error)
                Default set to 1e^-3
            rel_tolerance: float
                If the algorithm improves the accuracy less than re_tolerance, the algo stops
                Default set to 1e^-8
            max_iters: int
                Number of iterations for completion algo based on ALS scheme
            print_progress: boolean value
                If true it prints the progress of the algorithm


        Returns
        -------
        tensor : TT tensor
            it is a tt tensor (sciki_tt).

        train_error : numpy array 1D
             Array with training errors 

        validation_error : numpy array 1D
             Array with validation errors 


        Raises
        ------
        ValueError : 
             tolerance, rel_tolerance, max_iters have to be greater than 0
        TypeError : type mismatch
             max_iters has to be an integer
        TypeError : type mismatch
             print_progress has to be a boolean value
        """

        tolerance, rel_tolerance, max_iters, print_progress = self.__param_check_run_completion(**kwargs)

        train_error = -100 * np.ones(2 * max_iters)
        validation_error = -100 * np.ones(2 * max_iters)

        norm_subgrid_entries_train = np.linalg.norm(self.subgrid_vals_train)
        norm_subgrid_entries_val = np.linalg.norm(self.subgrid_vals_val)

        # if tensor.ranks[5] == 8:
        #     print(f"Shape core before orth inside completion algo: {tensor.cores[4].shape}\n")

        tensor = TTChebyshevUtils.orthogonalize(tensor, 0)

        # if tensor.ranks[5] == 8:
        #     print(f"Shape core after orth inside completion algo: {tensor.cores[4].shape}\n")

        for i in range(max_iters):

            # print('Forward sweep', '\n')
            # t0 = time.time()
            for core_idx in range(self.dimension - 1):
                # print(core_idx)
                core_mod = AlternatingLeastSquares.alternating_least_squares(
                    self.subgrid_entries_train, self.subgrid_vals_train, tensor, core_idx, self.num_cheb_pts_ptr,
                    self.sorted_entries_train_ptrs[core_idx])

                tensor.cores[core_idx] = core_mod  # place core_mod inside of tensor
                tensor = TTChebyshevUtils.orth_left(tensor, core_idx)

            ## -- Error collection for forward sweep
            err_train = self.__tensor_error(self.subgrid_entries_train,
                                            self.subgrid_vals_train, tensor)
            train_error[2 * i] = np.sqrt(2 * err_train) / norm_subgrid_entries_train

            err_val = self.__tensor_error(self.subgrid_entries_val,
                                          self.subgrid_vals_val, tensor)
            validation_error[2 * i] = np.sqrt(2 * err_val) / norm_subgrid_entries_val

            ## -- Error check to see if we exit algorithm
            if train_error[2 * i] < tolerance and validation_error[2 * i] < tolerance:
                if print_progress:
                    print("\n")
                    print("\tConverged at iteration: {}".format(i))
                    print("\tTrain error: {:.3e}".format(train_error[2 * i]))
                    print("\tValidation error {:.3e}".format(validation_error[2 * i]))
                    print("\tLeaving algo\n")

                train_error = train_error[0:2 * i + 1]
                validation_error = validation_error[0:2 * i + 1]
                return tensor, train_error, validation_error

            if i > 0:

                ## -- Stagnation check to see if we exit algorithm
                rel_tol = abs(train_error[2 * i] - train_error[2 * i - 1]) / train_error[2 * i]
                rel_tol_test = abs(validation_error[2 * i] - validation_error[2 * i - 1]) / \
                               validation_error[2 * i]

                if (rel_tol < rel_tolerance) and (rel_tol_test < rel_tolerance):
                    if print_progress:
                        print("\n")
                        print("\tAt iteration: {}".format(i))
                        print("\tRelative error change training: {:.3e}".format(rel_tol))
                        print("\tRelative error change testing: {:.3e}".format(rel_tol_test))
                        print("\tLeaving algo\n")

                    train_error = train_error[:2 * i + 1]
                    validation_error = validation_error[:2 * i + 1]
                    return tensor, train_error, validation_error

            # print('Backward sweep', '\n')
            for core_idx in range(self.dimension - 1, 0, -1):
                # print(core_idx)

                core_mod = AlternatingLeastSquares.alternating_least_squares(
                    self.subgrid_entries_train,
                    self.subgrid_vals_train, tensor, core_idx, self.num_cheb_pts_ptr,
                    self.sorted_entries_train_ptrs[core_idx])

                tensor.cores[core_idx] = core_mod  # place core_mod inside of tensor
                tensor = TTChebyshevUtils.orth_right(tensor, core_idx)

            ## -- Error collection for backward sweep
            error_train = self.__tensor_error(self.subgrid_entries_train,
                                              self.subgrid_vals_train, tensor)
            train_error[2 * i + 1] = np.sqrt(2 * error_train) / norm_subgrid_entries_train

            error_val = self.__tensor_error(self.subgrid_entries_val,
                                            self.subgrid_vals_val, tensor)
            validation_error[2 * i + 1] = np.sqrt(2 * error_val) / norm_subgrid_entries_val

            ## -- Error check to see if we exit algorithm
            if train_error[2 * i + 1] < tolerance and validation_error[2 * i + 1] < tolerance:
                if print_progress:
                    print("\n")
                    print("\tConverged at iteration: {}".format(i))
                    print("\tTrain error: {:.3e}".format(train_error[2 * i]))
                    print("\tValidation error {:.3e}".format(validation_error[2 * i]))
                    print("\tLeaving algo\n")

                train_error = train_error[:2 * i + 2]
                validation_error = validation_error[:2 * i + 2]
                return tensor, train_error, validation_error

            if i > 1:
                ## -- Stagnation check to see if we exit algorithm
                rel_tol = abs(train_error[2 * i + 1] - train_error[(2 * i + 1) - 1]) / \
                          train_error[2 * i + 1]
                rel_tol_test = abs(
                    validation_error[2 * i + 1] - validation_error[(2 * i + 1) - 1]) / \
                               validation_error[2 * i + 1]

                if (rel_tol < rel_tolerance) and (rel_tol_test < rel_tolerance):
                    if print_progress:
                        print("\n")
                        print("\tAt iteration: {}".format(i))
                        print("\tRelative error change training: {:.3e}".format(rel_tol))
                        print("\tRelative error change testing: {:.3e}".format(rel_tol_test))
                        print("\tLeaving algo\n")

                    train_error = train_error[:2 * i + 2]
                    validation_error = validation_error[:2 * i + 2]
                    return tensor, train_error, validation_error

        return tensor, train_error, validation_error

