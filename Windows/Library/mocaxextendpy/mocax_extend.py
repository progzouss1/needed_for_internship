    def subgrid_by_number(self, n):
        """
        Randomly sample n grid points. This creates the subgrid used to build the Chebyshev Tensor in TT format

        Subgrid is randomly generated. Subgrid points may be repeated in this sampling. Repeats are removed. Therefore, user should be aware that the number of subgrid points returned may be lower than the number requested..


        Parameters
        ----------
        n : int
             value greater than 0.

        Returns
        -------
        subgrid_points_unique : numpy array
             2  dimensional numpy array containing the subrid of the tensor for which we need values to run the rank adaptive algorithm

        Raises
        ------
        TypeError : type mismatch
             Parameter n must be an integer

        ValueError
             Parameter n must be greater than 1

        """
        if not isinstance(n, int):
            raise TypeError("Subrid must have at least two points. Only {} were asked for".format(n))
        elif n < 1:
            # if n and n > 1:
            raise ValueError("The parameter must be greater than 1")
        else:
            subgrid_points_unique = self.__sample_points_calculation(n)
            return subgrid_points_unique

    def subgrid_by_percent(self, p):
        """
        Randomly sample a subgrid of the full Chebyshev grid by specifying a percentage p. This creates the subgrid used to build the Chebyshev Tensor in TT format

        Subgrid is randomly generated. Subgrid points may be repeated in this sampling. Repeats are removed. Therefore, user should be aware that the number of subgrid points returned may be lower than the number requested..


        Parameters
        ----------
        p : float
             percentage between 0 and 1.

        Returns
        -------
        subgrid_points_unique : numpy array
             2  dimensional numpy array containing the subrid of the tensor for which we need values to run the rank adaptive algorithm

        Raises
        ------
        ValueError
            Parameter p must be between zero and one
        """

        if not (0 <= p <= 1):
            raise ValueError("Parameter p must be between 0 and 1")
        else:
            tensor_size = self.get_tensor_size()
            percentage = int(round(p * tensor_size))
            subgrid_points_unique = self.__sample_points_calculation(percentage)
            return subgrid_points_unique

    def __sample_points_calculation(self, n):
        """
        This method does the work for subgrid_by_number and subgrid_by_percent.
        It does the random sampling and removes repeats

        Parameters
        ----------
        n : int
             value greater than 0.

        Returns
        -------
        subgrid_points_unique : numpy array
             2  dimensional numpy array containing the subrid of the tensor for which we need values to run the rank adaptive algorithm

        """
        subgrid_entries = np.empty((n, self.dimension), dtype=int)
        subgrid_points = np.empty((n, self.dimension))
        for m, pt in enumerate(self.cheb_pts_per_dimension):
            rand_entries = np.random.choice(range(len(pt)), n)
            subgrid_entries[:, m] = rand_entries
            subgrid_points[:, m] = pt[rand_entries]

        _, indices = np.unique(subgrid_entries, axis=0, return_index=True)
        subgrid_entries_unique = subgrid_entries[np.sort(indices)]
        subgrid_points_unique = subgrid_points[np.sort(indices)]
        self.subgrid_entries = subgrid_entries_unique

        return subgrid_points_unique

    def set_subgrid(self, subgrid_points):
        """
        This method lets the user manually set subgrid.

        Parameters
        ----------
        subgrid_points : numpy array
             array of random cheb_pts. Note that these are not the entries representing the subgrid but the actual values.

        Raises
        ------
        ValueError : 
             subgrid_points must be 2D numpy array

        ValueError : NaN check
             subgrid_points must not contain NaN values

        ValueError : size mismatch
             subgrid_points must have as many columns as dimension specified for tensor (dimension is an attribute of class intance)

        """
        subgrid_points = np.array(subgrid_points)
        if subgrid_points.ndim == 2:
            if np.any(~np.isnan(subgrid_points)):
                if subgrid_points.shape[1] == self.dimension:
                    subgrid_entries = np.empty(subgrid_points.shape)
                    for m, pts in enumerate(subgrid_points):
                        for n, entry in enumerate(pts):
                            cheb_pts = self.cheb_pts_per_dimension[n]
                            if round(entry) in np.round(self.cheb_pts_per_dimension[n]):
                                idx = list(cheb_pts).index(entry)
                                subgrid_entries[m][n] = idx
                            else:
                                raise ValueError("Entry {} at location {} is not present in cheb "
                                                 "points.".format(entry, n))
                    self.subgrid_entries = subgrid_entries
                else:
                    raise ValueError("Subgrid_points columns must be equal to dimension.")
            else:
                raise ValueError("Subgrid_points must not contain NaN values.")
        else:
            raise ValueError("Subgrid_points should be 2 Dimensional Numpy Array.")

    def set_subgrid_values(self, values):
        """
        Stores the values corresponding the subgrid within the class instance.

        Parameters
        ----------
        values : numpy array 1D
             values for train and validation.

        Raises
        ------
        ValueError : dimension of values parameter
             values parameter should be a 1D numpy array

        AttributeError :
             subgrid_entries must already exist within the class for this method to be called

        ValueError : length check
             Length of values must be the same as length of subgrid_entries

        ValueError : NaN check
             Values param musst not contain NaN values
        """
        if np.ndim(values) == 1:
            if hasattr(self, "subgrid_entries"):
                if np.shape(self.subgrid_entries)[0] == len(values):
                    if not np.isnan(np.array(values)).any():
                        self.subgrid_vals = np.array(values)
                    else:
                        raise ValueError('Values must not contain NaN values.')
                else:
                    raise ValueError(
                        "Length of values: {}, must be equal to rows of subgrid_entries: {}.".format(len(values), self.subgrid_entries.shape[0]))
            else:
                raise AttributeError(
                    "To set values of a subgrid, the attribute subgrid_entries must exist already. First, call subgrid_by_number, subgrid_by_percent or set_subgrid, and then set corresponding values using set_subgrid_values")
        else:
            raise ValueError("The parameter values must be a 1D numpy array")

    def gen_train_val_data(self, **kwargs):
        """
        Function splits subgrid_entries and subgrid values into training and validation,If no split percentage is passed, function assumes 0.8


        Parameters
        ----------
        percentage : float
             percentage value for splitting tensor values.

        Raises
        ------
        ValueError : outside of range
             Percentage should be between 0 and 1.

        AttributeError :
             There is no data to generate training and validating data sets.First, call subgrid_by_number, subgrid_by_percent or set_subgrid, and set corresponding values using set_subgrid_values

        """
        if hasattr(self, "subgrid_vals") and hasattr(self, "subgrid_entries"):
            percentage = kwargs.get('percentage', 0.8)
            if 0 < percentage < 1:

                split_pct = int(percentage * len(self.subgrid_vals))
                self.subgrid_entries_train, self.subgrid_entries_val = \
                    self.subgrid_entries[:split_pct, :], self.subgrid_entries[split_pct:, :]

                split_val = int(percentage * len(self.subgrid_vals))
                self.subgrid_vals_train = self.subgrid_vals[:split_val]
                self.subgrid_vals_val = self.subgrid_vals[split_val:]

            else:
                raise ValueError("Percentage:{} should be between 0 and 1".format(percentage))
        else:
            raise AttributeError(
                "There is no data to generate training and validating data sets. First, call subgrid_by_number, subgrid_by_percent or set_subgrid, and set corresponding values using set_subgrid_values")

