class MocaxExtend(object):
    """
        Class that manages the run of the  Rank Adaptive Algorithm

        The class initialiser takes in the domain over which we build a Chebyshev Tensor in TT format and the number of Chebyshev points per dimension.

        To build the Chebyshev Tensor in TT format we need values on a subgrid of the Chebyshev grid. The subgrid can be randly generated by the class instance or may be set by the user.

        The subgrid must then be evaluated by the function to be approximated and stored within the class instance

        Once the subgrid and values on them are stored within the class instance, a training and validation set can be generated

        The Rank Adaptive algorithm can then be run. This generates the Chebyshev Tensor in TT format that approximates the function of interest.

        For more details on the algorithms implemented here, we refer to

        Steinlechner, M. Riemannian optimization for high-dimensional tensor completion. SIAM J. Sci. Comput. 38.  (2016). S461–S484.

        Glau, K. Kressner, F. Statti, F. Low-rank tensor approximation for Chebyshev interpolation in parametric option pricing. (2019) https://arxiv.org/abs/1902.04367


    """

    def __init__(self, dimension, num_cheb_pts, intervals):
        """
        Parameters
        ----------
        dimension : int
             Number of variables

        num_cheb_pts : list
             Number of Chebyshev points per dimension. Right now the number of Chebyshev points must be the same for all dimensions

        intervals : list of lists of floats
             List containing lists with two elements. Each list with two elements gives the range of a variable

        Raises
        ------
        ValueError
            dimension needs to be greater than 0
        ValueError
            dimension must be greater than 0
        ValueError
            When length of num_cheb_pts does not match dimension
        TypeError : type mismatch
            Entries in num_cheb_pts must all be integers
        ValueError
            All entries in num_cheb_pts must have the same value
        ValueError
            When intervals are not of length 2
        ValueError
            When number of intervals is not the same as dimension
        """

        self.dimension = dimension
        self.num_cheb_pts = num_cheb_pts
        self.intervals = intervals  # Only used for the generation of Cheb points per dimension
        self.__cheb_pts_tensor()

