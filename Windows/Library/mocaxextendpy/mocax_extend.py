    def __gen_sorted_subgrid_train_ptr(self):

        """
        Generates gen_subgrid_train_ptr used in alternating least squares scheme
        sorted_entries_train_ptrs  is a dictonary of ctype arrays with integers
        It is important to generated it before the als routine is run to speed the code
        """

        self.sorted_entries_train_ptrs = {}
        for core_idx in range(self.dimension):
            sorted_tensor_entries_train, sorted_values_train, __ = AlternatingLeastSquares.sort_tensor_pts(
                self.subgrid_entries_train, self.subgrid_vals_train, core_idx)

            ## -- Indices
            sorted_entries = np.array(sorted_tensor_entries_train.tolist(), dtype=np.intc)
            sorted_entries_ptr = sorted_entries.ctypes.data_as(ctypes.POINTER(ctypes.c_int * sorted_entries.size))
            self.sorted_entries_train_ptrs[core_idx] = sorted_entries_ptr

