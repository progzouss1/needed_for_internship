    def run_rank_adaptive_algo(self, **kwargs):
        """
        This method runs the rank adaptive algorithm.

        Parameters
        ----------
        **kwargs : algorithm parameters
            tolerance: float
                Accuracy of approximation we want to reach (relative error)
                Default set to 1e^-3
            rel_tolerance: float
                If the algorithm improves the accuracy less than re_tolerance, the algo stops
                Default set to 1e^-8
            max_iters: int
                Number of iterations for completion algo based on ALS scheme
                Default set to 50
            print_progress: boolean value
                If true it prints the progress of the algorithm
                Default set to false
            max_rank: int
                Maximum rank of core that we let the rank adaptive algorithm reach
                Default set to the minimum number of Cheb points per dimension
            max_rounds: int
                Maximum number of times the rank is increased for every core without improvement
                Default set to 5
            epsilon: float
                Used when randomly generating values to extend rank of cores
                Default set to 1e-8
        """
        # Check that params that have been passed have the right type
        if hasattr(self, "subgrid_entries_train"):
            if hasattr(self, "subgrid_vals_train"):
                if hasattr(self, "subgrid_entries_val"):
                    if hasattr(self, "subgrid_vals_val"):
                        tolerance, rel_tolerance, max_iters, epsilon, max_rank, print_progress, max_rounds = \
                            self.__param_check_rank_adaptive(**kwargs)

                        # Generate some of the pointers needed for the function wrappers of C code
                        self.__gen_num_cheb_pts_ptr()
                        self.__gen_sorted_subgrid_train_ptr()

                        # Randomly generate a tt tensor
                        cores = [np.random.rand(1, self.num_cheb_pts[n] + 1, 1, 1)
                                 for n in range(self.dimension)]
                        tensor_init = TT(cores)
                        tensor, train_error, validation_error = self.run_completion_algo(tensor_init, **kwargs)
                        validation_error_old = validation_error[-1]

                        curr_max_rank = 0
                        curr_round = 0
                        max_rounds = 5 * self.dimension

                        if print_progress:
                            print("_________________________________________")
                        while curr_max_rank < max_rank and curr_round < max_rounds:
                            for i in range(1, self.dimension):
                                ## -- Increase rank
                                if print_progress:
                                    print("\nCurrent tensor: {}".format(tensor))
                                    print("\nTrying increase rank {} from {} to {}".format(i, tensor.ranks[i],
                                                                                           tensor.ranks[i] + 1))

                                tensor_new = MocaxExtend.__increase_rank(tensor, i, epsilon)

                                # if print_progress:
                                #     print("\nNew tensor: {}".format(tensor_new))


                                tensor_new = TTChebyshevUtils.orthogonalize(tensor_new, self.dimension - 1)

                                # if i == 5 and tensor_new.ranks[5] == 8:
                                #     print(f"After ortho idx: {tensor_new.cores[i].shape}")
                                #     print(f"After ortho idx - 1: {tensor_new.cores[i-1].shape}\n")

                                tensor_new, train_error_new, validation_error_new = self.run_completion_algo(
                                    tensor_new, **kwargs)

                                ## -- Print message to keep track of error
                                if print_progress:
                                    print("\nCurrent train cost: {:.3e}".format(train_error_new[-1]))
                                    print("Current validation cost: {:.3e}".format(validation_error_new[-1]))

                                if (train_error_new[-1] < tolerance) and (validation_error_new[-1] < tolerance):
                                    if print_progress:
                                        print(
                                            "\nAPPROX ERROR TRAIN BELOW THRESHOLD: {:.3e}".format(train_error_new[-1]))
                                        print("APPROX ERROR VALIDATION BELOW THRESHOLD: {:.3e}".format(
                                            validation_error_new[-1]))
                                        print("_________________________________________")
                                    tensor = tensor_new
                                    self.trained_tt_tensor = tensor
                                    return None

                                rel_progress = (validation_error_new[-1] - validation_error_old) / validation_error_old
                                progress = (validation_error_new[-1] - validation_error_old)
                                if print_progress:
                                    print("\nError improvement of {:.3e} in rank increase attempt".format(progress))

                                if progress > 0:
                                    if print_progress:
                                        print("\nFAILED with completion algo. Reverting to old tensor")
                                    curr_round = curr_round + 1
                                    if print_progress:
                                        print("Current round: {}".format(curr_round))
                                        print("_________________________________________")

                                else:
                                    if print_progress:
                                        print("\nSUCCEEDED with completion algo. Updating to new tensor")
                                    tensor = tensor_new
                                    validation_error_old = validation_error_new[-1]
                                    curr_max_rank = max(tensor.ranks)
                                    if print_progress:
                                        print("\nCurrent max rank {}".format(curr_max_rank))
                                    curr_round = 0
                                    if print_progress:
                                        print("_________________________________________")

                                if curr_round >= max_rounds:
                                    if print_progress:
                                        print(
                                            "\nEXIT RANK ADAPTIVE AS CURR_ROUND {} EXCEEDED MAX LOCKS {}\n".format(
                                                curr_round, max_rounds))
                                    self.trained_tt_tensor = tensor
                                    return None
                                if curr_max_rank >= max_rank:
                                    if print_progress:
                                        print(
                                            "\nEXIT RANK ADAPTIVE AS MAX RANK {} EXCEEDED MAXIMUM RANK CHOSEN IN PARAMS {}\n".format(
                                                curr_max_rank, max_rank))
                                    self.trained_tt_tensor = tensor
                                    return None
                    else:
                        raise AttributeError("Subgrid_vals_val attribute are needed but have not been generated")
                else:
                    raise AttributeError("Subgrid_entries_val attribute are needed but have not been generated")
            else:
                raise AttributeError("Subgrid_vals_train attribute are needed but have not been generated")
        else:
            raise AttributeError("Subgrid_entries_train attribute are needed but have not been generated")

